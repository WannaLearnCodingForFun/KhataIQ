"""Golden-file and error tests for the digital-PDF parser.
Fixtures are generated by tests/fixtures/make_pdf_fixture.py."""

import json
from dataclasses import asdict
from pathlib import Path

import pytest

from khataiq.core.ledger import Txn, reconcile
from khataiq.pipeline.parsers import get_parser
from khataiq.pipeline.parsers.base import ParseError

PDFS = Path(__file__).parent / "fixtures" / "demo_pdf"


def parse(name: str):
    return get_parser("demo", "pdf_text").parse((PDFS / name).read_bytes())


def test_pdf_matches_golden_output():
    data = asdict(parse("statement_dec.pdf"))
    for row in data["rows"]:
        row["txn_date"] = row["txn_date"].isoformat()
    assert data == json.loads((PDFS / "statement_dec.expected.json").read_text())


def test_repeated_header_on_page_two_is_dropped():
    s = parse("statement_dec.pdf")
    assert len(s.rows) == 48
    assert all(r.narration.lower() != "narration" for r in s.rows)
    assert s.rows[30].line_no == 2001  # first row on page 2


def test_pdf_statement_reconciles():
    s = parse("statement_dec.pdf")
    txns = [Txn(i, 1, r.txn_date, r.amount_paise, r.direction, r.balance_after_paise,
                r.narration, r.utr) for i, r in enumerate(s.rows)]
    assert reconcile(s.opening_paise, s.closing_paise, txns).ok


def test_pdf_without_text_layer_is_rejected():
    with pytest.raises(ParseError) as err:
        parse("no_text.pdf")
    assert (err.value.line_no, err.value.message) == (0, "no text layer")


def test_garbage_bytes_are_not_a_pdf():
    with pytest.raises(ParseError) as err:
        get_parser("demo", "pdf_text").parse(b"definitely not a pdf")
    assert err.value.line_no == 0
