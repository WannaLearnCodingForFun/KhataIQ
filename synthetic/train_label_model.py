"""Train the label model on synthetic businesses and measure it against rules alone.

    python -m synthetic.train_label_model --businesses 250 --seed 1 --out models/label/v1

Businesses (not rows) are split 80/20, so no business contributes rows to both training and
evaluation. Three systems are scored on the held-out businesses with macro-F1:
  rules only        a rule's label, else 'other'
  model only        the model on every row
  rules + model     what the pipeline runs: a rule's label, else the model's
Writes the model, its card.json, and docs/results/label_model.md.
"""

from __future__ import annotations

import argparse
from datetime import UTC, datetime
from pathlib import Path

from sklearn.metrics import classification_report, f1_score

from khataiq.classify.model import LabelModel, build_pipeline, features, save
from khataiq.classify.rules import RULES_VERSION, rule_label
from khataiq.core.ledger import normalize_narration
from synthetic.generator import generate

Row = tuple[str, str, int, str]  # narration_norm, direction, amount_paise, true label


def business_rows(seed: int) -> list[Row]:
    biz = generate(seed)
    return [(normalize_narration(r.narration), "credit" if r.credit else "debit",
             r.credit or r.debit, r.label) for r in biz.rows.values()]


def rules_only(rows: list[Row]) -> list[str]:
    out = []
    for narration, direction, _, _ in rows:
        rule = rule_label(narration, direction)
        out.append(rule.label.value if rule else "other")
    return out


def main() -> None:
    parser = argparse.ArgumentParser(description="Train the transaction label model")
    parser.add_argument("--businesses", type=int, default=250)
    parser.add_argument("--seed", type=int, default=1)
    parser.add_argument("--version", default="label-v1")
    parser.add_argument("--out", type=Path, default=Path("models/label/v1"))
    parser.add_argument("--report", type=Path, default=Path("docs/results/label_model.md"))
    args = parser.parse_args()

    seeds = list(range(args.seed, args.seed + args.businesses))
    cut = int(len(seeds) * 0.8)
    train = [row for seed in seeds[:cut] for row in business_rows(seed)]
    test = [row for seed in seeds[cut:] for row in business_rows(seed)]

    pipeline = build_pipeline()
    pipeline.fit([features(n, d, a) for n, d, a, _ in train], [label for *_, label in train])
    model = LabelModel(args.version, pipeline, {})

    truth = [label for *_, label in test]
    by_rules = rules_only(test)
    by_model = [p.label for p in model.predict([(n, d, a) for n, d, a, _ in test])]
    combined = [r if r != "other" or rule_label(n, d) else m
                for r, m, (n, d, _, _) in zip(by_rules, by_model, test, strict=True)]
    labels = sorted(set(truth))
    scores = {name: round(float(f1_score(truth, pred, labels=labels, average="macro",
                                         zero_division=0)), 3)
              for name, pred in [("rules_only", by_rules), ("model_only", by_model),
                                 ("rules_plus_model", combined)]}
    rule_coverage = sum(1 for n, d, _, _ in test if rule_label(n, d)) / len(test)

    model.card = {
        "version": args.version,
        "created": datetime.now(UTC).date().isoformat(),
        "rules_version": RULES_VERSION,
        "features": "TF-IDF char_wb 2-5 grams over 'DR|CR AMT<digits> <narration>'",
        "classifier": "LogisticRegression(class_weight='balanced')",
        "confidence_floor": 0.6,
        "training_data": (f"synthetic.generator seeds {seeds[0]}-{seeds[cut - 1]} "
                          f"({cut} businesses, {len(train)} rows)"),
        "evaluation_data": (f"held-out businesses, seeds {seeds[cut]}-{seeds[-1]} "
                            f"({len(seeds) - cut} businesses, {len(test)} rows)"),
        "macro_f1": scores,
        "rule_coverage": round(rule_coverage, 3),
    }
    save(model, args.out)
    report = classification_report(truth, combined, labels=labels, zero_division=0, digits=3)
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(render(model.card, report))
    print(scores)


def render(card: dict[str, object], report: str) -> str:
    scores = card["macro_f1"]
    assert isinstance(scores, dict)
    return "\n".join([
        "# Transaction label model",
        "",
        "Generated by `python -m synthetic.train_label_model`. Synthetic data only: these numbers "
        "show the model learns the generator's narration patterns, not that it labels real "
        "statements well.",
        "",
        f"- Model `{card['version']}`: {card['features']}, {card['classifier']}, "
        f"predictions under {card['confidence_floor']} confidence become `other`.",
        f"- Trained on {card['training_data']}.",
        f"- Evaluated on {card['evaluation_data']}; split by business, never by row.",
        f"- Rules ({card['rules_version']}) label {float(card['rule_coverage']):.0%} of "  # type: ignore[arg-type]
        "held-out rows on their own.",
        "",
        "| System | Macro-F1 |",
        "| --- | ---: |",
        f"| Rules only (unmatched rows → `other`) | {scores['rules_only']:.3f} |",
        f"| Model only | {scores['model_only']:.3f} |",
        f"| **Rules + model (what the pipeline runs)** | **{scores['rules_plus_model']:.3f}** |",
        "",
        "## Per label, rules + model",
        "",
        "```",
        report.rstrip(),
        "```",
        "",
        "## What this does and doesn't show",
        "",
        "- Person and firm names come from small fixed pools, so held-out businesses share "
        "names with training businesses. Real narrations are far more varied.",
        "- Some labels can't be told apart from the narration alone: a salary and a rent "
        "payment to a person by NEFT look the same; a self-transfer by UPI looks like a "
        "customer payment. The evidence engine, not the label model, decides transfers.",
        "- A small transformer was not tried: the baseline is the honest first step, and the "
        "spec only adds one if it beats the baseline by 3+ macro-F1 points on real data, "
        "which this project doesn't have.",
        "",
    ])


if __name__ == "__main__":
    main()
